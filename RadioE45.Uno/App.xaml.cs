public partial class App : Application
{
    public App()
    {
        InitializeComponent();
    }

    /// <summary>
    /// Root service provider. Pages created by the Frame (parameterless constructors) resolve
    /// their ViewModel from here.
    /// </summary>
    public static IServiceProvider Services { get; private set; } = null!;

    protected Window? MainWindow { get; private set; }

    protected IHost? Host { get; private set; }

    [SuppressMessage("Trimming", "IL2026", Justification = "Uno.Extensions hosting as generated by the unoapp template.")]
    protected override async void OnLaunched(LaunchActivatedEventArgs args)
    {
        var builder = this.CreateBuilder(args)
            .Configure(host => host
#if DEBUG
                .UseEnvironment(Environments.Development)
#endif
                .UseLogging(configure: (context, logBuilder) =>
                {
                    logBuilder
                        .SetMinimumLevel(context.HostingEnvironment.IsDevelopment() ? LogLevel.Information : LogLevel.Warning)
                        .CoreLogLevel(LogLevel.Warning);
                }, enableUnoLogging: true)
                .ConfigureServices((_, services) => ConfigureServices(services)));

        MainWindow = builder.Window;
        MainWindow.Title = "Radio E45";
        MainWindow.SetWindowIcon();

        Host = builder.Build();
        Services = Host.Services;
        Services.GetRequiredService<UnoWindowHost>().Attach(MainWindow);

        // Before anything touches the file system (SQLite): on the web this waits for IDBFS.
        await Services.GetRequiredService<UnoAppPaths>().InitializeAsync();
#if RADIOE45_BROWSER
        // Before On Air starts: whether the browser lets the radio start without a click.
        await RadioE45.Services.Browser.BrowserUserActivation.ProbeAsync();
        RadioE45.Services.Browser.BrowserUserActivation.WatchBlockedPlays();
#endif

        MainWindow.Content ??= Services.GetRequiredService<ShellPage>();

        var settings = Services.GetRequiredService<ISettingsStore>();
        Services.GetRequiredService<IThemeService>()
            .Apply(settings.Get(UnoThemeService.PreferenceKey, UnoThemeService.DefaultPreference));
#if RADIOE45_DESKTOP
        ApplyDesktopWindowSize(MainWindow, settings);
#endif

        MainWindow.Activate();

#if DEBUG && RADIOE45_DESKTOP
        if (PlatformSelfTest.IsRequested)
            MainWindow.DispatcherQueue.TryEnqueue(async () =>
            {
                await PlatformSelfTest.RunAsync(Services);
                Exit();
            });
#endif
    }

#if RADIOE45_DESKTOP
    /// <summary>
    /// Same fixed window as the MAUI desktop heads (500×855 or 900×450 logical units, not
    /// resizable). AppWindow.Resize takes physical pixels of the client area, so the size is
    /// scaled by the display's rasterization scale, known once the content is loaded.
    /// </summary>
    private static void ApplyDesktopWindowSize(Window window, ISettingsStore settings)
    {
        var (width, height) = DesktopWindowSize.For(settings);

        void Resize(double scale)
        {
            var size = new Windows.Graphics.SizeInt32
            {
                Width = (int)Math.Round(width * scale),
                Height = (int)Math.Round(height * scale),
            };
            window.AppWindow.Resize(size);

            if (window.AppWindow.Presenter is Microsoft.UI.Windowing.OverlappedPresenter presenter)
            {
                presenter.IsResizable = false;
                presenter.IsMaximizable = false;
                presenter.PreferredMinimumWidth = size.Width;
                presenter.PreferredMinimumHeight = size.Height;
            }
        }

        if (window.Content is not FrameworkElement root)
            return;
        if (root.XamlRoot is { } xamlRoot)
        {
            Resize(xamlRoot.RasterizationScale);
            return;
        }

        void OnLoaded(object sender, RoutedEventArgs e)
        {
            root.Loaded -= OnLoaded;
            Resize(root.XamlRoot?.RasterizationScale ?? 1.0);
        }
        root.Loaded += OnLoaded;
    }
#endif

    private static void ConfigureServices(IServiceCollection services)
    {
        // Platform services shared by desktop and web (Services/Shared), plus the head-specific
        // ones (Services/Desktop, Services/Browser). Same registrations as RadioE45/MauiProgram.cs.
        services.AddSingleton<UnoWindowHost>();
        services.AddSingleton<IUiDispatcher, UnoUiDispatcher>();
        services.AddSingleton<IDialogService, UnoDialogService>();
        services.AddSingleton<ISettingsStore, UnoSettingsStore>();
        services.AddSingleton<IAppEnvironment, UnoAppEnvironment>();
        services.AddSingleton<IUrlLauncher, UnoUrlLauncher>();
        services.AddSingleton<IThemeService, UnoThemeService>();
        services.AddSingleton<UnoNavigationService>();
        services.AddSingleton<INavigationService>(sp => sp.GetRequiredService<UnoNavigationService>());
        services.AddSingleton<UnoAppPaths>();
        services.AddSingleton<IAppPaths>(sp => sp.GetRequiredService<UnoAppPaths>());
        services.AddSingleton<ICrashReportingService, UnavailableCrashReportingService>();
#if RADIOE45_DESKTOP
        services.AddSingleton<INetworkMonitor, Services.Desktop.DesktopNetworkMonitor>();
#elif RADIOE45_BROWSER
        services.AddSingleton<INetworkMonitor, Services.Browser.BrowserNetworkMonitor>();
#endif

        services.AddRadioE45Core();

        // Update check (docs/APP-UPDATE-ROADMAP.md): the Linux .deb follows GitHub Releases, the web build its own
        // version.json; the other desktops have no check. Replaces the NullUpdateSource of AddRadioE45Core.
#if RADIOE45_BROWSER
        services.AddSingleton<IAppUpdateSource>(sp =>
        {
            // Resolved while the shell is built: a failure here must not stop the app from starting.
            try
            {
                return new WebVersionUpdateSource(sp.GetRequiredService<IHttpClientFactory>(), global::RadioE45.Services.Browser.BrowserAppBase.Get());
            }
            catch (Exception ex)
            {
                sp.GetRequiredService<ILoggerFactory>().CreateLogger("UpdateCheck").LogWarning(ex, "Web update check unavailable");
                return new NullUpdateSource();
            }
        });
#else
        if (OperatingSystem.IsLinux())
        {
            services.AddSingleton<IAppUpdateSource>(sp =>
                new GitHubReleaseUpdateSource(sp.GetRequiredService<IHttpClientFactory>(), GitHubReleaseChannel.LinuxDeb));
        }
#endif

        // Audio: shared live and podcast engines on the Uno MediaPlayer. System media controls:
        // MPRIS on Linux (nothing on macOS and Windows), Media Session on the web.
        services.AddSingleton<IAudioService, UnoAudioService>();
        services.AddSingleton<IPodcastPlayerService, UnoPodcastPlayerService>();
        services.AddSingleton<SystemMediaCommands>();
#if RADIOE45_DESKTOP
        services.AddSingleton<IPlatformNowPlayingService, Services.Desktop.MprisNowPlayingService>();
#elif RADIOE45_BROWSER
        services.AddSingleton<IPlatformNowPlayingService, Services.Browser.BrowserMediaSession>();
        // Replaces the Core prober: a fetch can be refused where the audio element plays.
        services.AddSingleton<IStreamUrlProber, Services.Browser.BrowserStreamUrlProber>();
#endif
        services.AddSingleton<IAudioFocusManager, NullAudioFocusManager>();

        services.AddSingleton<IAzuraStationCatalog, AzuraStationCatalog>();
        services.AddSingleton<IDatabaseService, DatabaseService>();

        // ViewModels, same lifetimes as MAUI.
        services.AddSingleton<OnAirViewModel>();
        services.AddSingleton<AppMenuViewModel>();
        services.AddTransient<RadioListViewModel>();
        services.AddTransient<AddStationViewModel>();
        services.AddTransient<EditStationViewModel>();
        services.AddTransient<SettingsViewModel>();
        // One instance like the MAUI tab page: it subscribes to OnAirViewModel to follow the
        // station, so a new one at every visit of the tab would stay subscribed forever.
        services.AddSingleton<PodcastListViewModel>();
        services.AddTransient<PodcastEpisodesViewModel>();
        services.AddTransient<SongRequestViewModel>();
        services.AddTransient<ScheduleViewModel>();

        services.AddTransient<ShellPage>();
    }
}
