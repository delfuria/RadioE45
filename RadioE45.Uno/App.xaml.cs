using System.Diagnostics.CodeAnalysis;
using RadioE45.DependencyInjection;
using RadioE45.Services.Platform;
using RadioE45.Services.Shared;
using RadioE45.Views;
using Uno.Resizetizer;

namespace RadioE45;

public partial class App : Application
{
    public App()
    {
        InitializeComponent();
    }

    /// <summary>
    /// Root service provider. Pages created by the Frame (parameterless constructors) resolve
    /// their ViewModel from here.
    /// </summary>
    public static IServiceProvider Services { get; private set; } = null!;

    protected Window? MainWindow { get; private set; }

    protected IHost? Host { get; private set; }

    [SuppressMessage("Trimming", "IL2026", Justification = "Uno.Extensions hosting as generated by the unoapp template.")]
    protected override void OnLaunched(LaunchActivatedEventArgs args)
    {
        var builder = this.CreateBuilder(args)
            .Configure(host => host
#if DEBUG
                .UseEnvironment(Environments.Development)
#endif
                .UseLogging(configure: (context, logBuilder) =>
                {
                    logBuilder
                        .SetMinimumLevel(context.HostingEnvironment.IsDevelopment() ? LogLevel.Information : LogLevel.Warning)
                        .CoreLogLevel(LogLevel.Warning);
                }, enableUnoLogging: true)
                .ConfigureServices((_, services) => ConfigureServices(services)));

        MainWindow = builder.Window;
        MainWindow.Title = "Radio E45";
        MainWindow.SetWindowIcon();

        Host = builder.Build();
        Services = Host.Services;

        MainWindow.Content ??= Services.GetRequiredService<ShellPage>();
        MainWindow.Activate();
    }

    private static void ConfigureServices(IServiceCollection services)
    {
        // Platform services (Services/Shared: desktop + web). Only navigation in S6a; dispatcher,
        // dialogs, settings, app environment, URL launcher and theme follow in S6b, paths,
        // network, audio and crash reporting in S7 (docs/LINUX-UNO-ROADMAP.md).
        services.AddSingleton<UnoNavigationService>();
        services.AddSingleton<INavigationService>(sp => sp.GetRequiredService<UnoNavigationService>());

        services.AddRadioE45Core();

        services.AddTransient<ShellPage>();
    }
}
