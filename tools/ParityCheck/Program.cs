// MAUI ↔ Uno UI parity checker. See docs/LINUX-UNO-ROADMAP.md §6.3.
//
//   dotnet run --project tools/ParityCheck -- [--strict] [--include-tv] [--strict-tv] [--json] [--update-surface] [--root <dir>]
//
// --strict            declared 'todo' on desktop/web is an error (release gate of the Uno app)
// --include-tv        lists 'todo' on tv feature by feature (informational)
// --strict-tv         declared 'todo' on tv is an error (release gate of the Android TV app,
//                     docs/ANDROID-TV-ROADMAP.md §5); independent of --strict. On tv 'n/a' is a
//                     permanent, legitimate answer: the gate asks that every feature is decided.
//
// Exit codes: 0 aligned; 1 only declared debt or warnings; 2 undeclared drift (blocks).

using System.Text.Encodings.Web;
using System.Text.Json;
using RadioE45.ParityCheck;
using RadioE45.ViewModels;

var strict = args.Contains("--strict");
var includeTv = args.Contains("--include-tv");
var strictTv = args.Contains("--strict-tv");
var json = args.Contains("--json");
var updateSurface = args.Contains("--update-surface");
var rootIndex = Array.IndexOf(args, "--root");
var root = rootIndex >= 0 && rootIndex + 1 < args.Length ? Path.GetFullPath(args[rootIndex + 1]) : FindRoot();

if (root is null)
{
    Console.Error.WriteLine("ParityCheck: RadioE45.slnx not found in the current directory or its parents (use --root).");
    return 2;
}

var coreAssembly = typeof(BaseViewModel).Assembly;

if (updateSurface)
{
    var lines = VmSurface.Generate(coreAssembly);
    var header = "# Public surface of the RadioE45.Core ViewModels (generated by tools/ParityCheck --update-surface).\n" +
                 "# Update it together with parity/features.yaml: see docs/LINUX-UNO-ROADMAP.md §6.3.\n";
    File.WriteAllText(Path.Combine(root, ParityChecker.SurfacePath), header + VmSurface.ToText(lines));
    Console.Error.WriteLine($"ParityCheck: {ParityChecker.SurfacePath} updated ({lines.Count} lines).");
}

var findings = new ParityChecker(root, coreAssembly).Run(strict, includeTv, strictTv);
var exitCode = findings.Any(f => f.Severity == Severity.Error) ? 2
    : findings.Count > 0 ? 1
    : 0;

if (json)
{
    var report = new
    {
        exitCode,
        errors = findings.Where(f => f.Severity == Severity.Error).Select(f => new { f.Check, f.Message }),
        warnings = findings.Where(f => f.Severity == Severity.Warning).Select(f => new { f.Check, f.Message }),
        debt = findings.Where(f => f.Severity == Severity.Debt).Select(f => new { f.Check, f.Message }),
    };
    Console.WriteLine(JsonSerializer.Serialize(report, new JsonSerializerOptions
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    }));
}
else
{
    foreach (var group in findings.GroupBy(f => f.Severity).OrderBy(g => g.Key))
    {
        Console.WriteLine($"{group.Key switch { Severity.Error => "ERRORS", Severity.Warning => "WARNINGS", _ => "DECLARED DEBT" }} ({group.Count()})");
        foreach (var f in group)
            Console.WriteLine($"  [{f.Check}] {f.Message}");
        Console.WriteLine();
    }

    Console.WriteLine(exitCode switch
    {
        0 => "ParityCheck: OK, MAUI, Uno and TV are aligned.",
        1 => "ParityCheck: no undeclared drift (only declared debt/warnings).",
        _ => "ParityCheck: UNDECLARED DRIFT. Fix the errors above or declare the debt in parity/features.yaml.",
    });
}

return exitCode;

static string? FindRoot()
{
    for (var dir = new DirectoryInfo(Directory.GetCurrentDirectory()); dir is not null; dir = dir.Parent)
    {
        if (File.Exists(Path.Combine(dir.FullName, "RadioE45.slnx")))
            return dir.FullName;
    }

    return null;
}
